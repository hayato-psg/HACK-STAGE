type FpSeed = [FootprintUserType, string, string, string, string, number];

// スポットの周りに足跡を配置する（決定的なオフセットで毎回同じ見た目に）
function footprints(spotId: string, lat: number, lng: number, seeds: FpSeed[]): Footprint[] {
  return seeds.map(([userType, userName, profile, date, comment, rating], i) => {
    const angle = (i * 137.5 * Math.PI) / 180;
    const r = 0.0006 + (i % 3) * 0.0004;
    return {
      id: `${spotId}-fp-${i + 1}`,
      spotId,
      userName,
      userType,
      profile,
      date,
      comment,
      rating,
      lat: lat + Math.sin(angle) * r,
      lng: lng + Math.cos(angle) * r,
    };
  });
}

function spot(s: Omit<Spot, 'footprints'>, seeds: FpSeed[]): Spot {
  return { ...s, footprints: footprints(s.id, s.lat, s.lng, seeds) };
}

